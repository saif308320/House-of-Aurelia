export function uniqueQueue(list) {
  const seen = new Set()
  const q = []
  for (const u of list) {
    if (!seen.has(u)) { seen.add(u); q.push(u) }
  }
  return q
}

export function takeShots(queue, n = 3) {
  const out = []
  for (let i = 0; i < n && queue.length; i++) out.push(queue.shift())
  return out
}
